"""Планировщик: строит план разделов возражения и выявляет пробелы в данных."""

from __future__ import annotations

import json

from agents.llm import call_json

SYSTEM = """Ты — Планировщик. На вход — JSON от Аналитика (факты дела и список требований).

Верни СТРОГО JSON:
{
  "plan": ["Фактические обстоятельства", "<раздел на каждое требование>",
           "Ходатайство об отсрочке", "ПРОШУ СУД", "Приложения"],
  "needed_data": [{"requirement": "...", "what": "какие нормы/расчёты нужны"}],
  "open_questions": ["короткие вопросы юристу, если данных не хватает или они противоречивы"]
}

Логика:
- На КАЖДОЕ требование из анализа — отдельный раздел.
- Раздел «Ходатайство об отсрочке» включай всегда (ПП РФ № 326).
- Если для расчёта неустойки за просрочку нет цены договора, даты передачи или
  ключевой ставки — внеси КОНКРЕТНЫЙ вопрос в open_questions.
- Если есть ocr_warnings — добавь вопрос на подтверждение сомнительных данных.
- open_questions — пустой массив, если всё ясно.
- Только JSON."""


def plan(analysis: dict) -> dict:
    """Построить план по результату Аналитика."""
    data = call_json(SYSTEM, json.dumps(analysis, ensure_ascii=False))
    data.setdefault("plan", [])
    data.setdefault("needed_data", [])
    data.setdefault("open_questions", [])
    return data
